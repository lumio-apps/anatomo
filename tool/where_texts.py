def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "assets", "content")
    for key, linked in LINKS.items():
        assert key in KEYS, key
        for other in linked:
            assert other in KEYS and other != key, (key, other)
    for lang, texts in W.items():
        if len(texts) != len(KEYS):
            raise SystemExit(f"{lang}: {len(texts)} texts for {len(KEYS)} parts")
        data = {"where": dict(zip(KEYS, texts))}
        with open(os.path.join(out, f"{lang}_w.json"), "w", encoding="utf-8") as fh:
            json.dump(data, fh, ensure_ascii=False, indent=1)
            fh.write("\n")
    with open(os.path.join(out, "links.json"), "w", encoding="utf-8") as fh:
        json.dump({k: LINKS[k] for k in KEYS}, fh, ensure_ascii=False, indent=1)
        fh.write("\n")
    print("wrote", len(W), "languages and links.json")


if __name__ == "__main__":
    main()
