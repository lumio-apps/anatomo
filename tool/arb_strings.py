def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "lib", "l10n")
    os.makedirs(out, exist_ok=True)
    base = S["en"]
    for lang, strings in S.items():
        missing = set(base) - set(strings)
        extra = set(strings) - set(base)
        if missing or extra:
            raise SystemExit(f"{lang}: missing {sorted(missing)} extra {sorted(extra)}")
        data = {"@@locale": lang}
        for key in base:
            data[key] = strings[key]
            for name in PLACEHOLDERS.get(key, {}):
                if "{" + name + "}" not in strings[key]:
                    raise SystemExit(f"{lang}.{key} lacks {{{name}}}")
            if lang == "en" and key in PLACEHOLDERS:
                data["@" + key] = {
                    "placeholders": {n: {"type": t} for n, t in PLACEHOLDERS[key].items()}
                }
        with open(os.path.join(out, f"app_{lang}.arb"), "w", encoding="utf-8") as fh:
            json.dump(data, fh, ensure_ascii=False, indent=2)
            fh.write("\n")
    print("wrote", len(S), "files")


